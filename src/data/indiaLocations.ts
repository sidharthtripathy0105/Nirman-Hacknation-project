export function buildGeoLocationFromDistrict(
  stateName: string,
  district: DistrictHub,
  customStreetAddress?: string
): GeoLocation {
  const cleanCity = `${district.name}, ${stateName}`.slice(0, 80);
  const defaultAddress = `${district.name} Commercial Logistics Hub, ${stateName}, India`;
  return {
    city: cleanCity,
    address: (customStreetAddress?.trim() || defaultAddress).slice(0, 300),
    lat: district.lat,
    lng: district.lng,
  };
}
